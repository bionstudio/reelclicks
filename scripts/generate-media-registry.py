"""Regenerates src/lib/content/sample-media.ts from public/images/demo.
Run: python scripts/generate-media-registry.py   (requires Pillow)"""
import os, base64, io, json
from PIL import Image, ImageFilter
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = os.path.join(ROOT, "public", "images", "demo")
out = ["/* AUTO-GENERATED by scripts/generate-media-registry.py — do not edit by hand. */",
       "/* Placeholder photography (Unsplash licence). Replace with REELCLICKS footage stills. */", "",
       "export const sampleMedia = {"]
for f in sorted(os.listdir(IMG)):
    if not f.endswith(".jpg"): continue
    im = Image.open(os.path.join(IMG, f)).convert("RGB")
    w, h = im.size
    t = im.copy(); t.thumbnail((16, 16)); t = t.filter(ImageFilter.GaussianBlur(0.6))
    b = io.BytesIO(); t.save(b, "JPEG", quality=45)
    blur = "data:image/jpeg;base64," + base64.b64encode(b.getvalue()).decode()
    key = f[:-4]
    out.append(f'  {json.dumps(key)}: {{ src: "/images/demo/{f}", width: {w}, height: {h}, blurDataURL: {json.dumps(blur)} }},')
out.append("} as const;\n\nexport type SampleMediaKey = keyof typeof sampleMedia;\n")
open(os.path.join(ROOT, "src", "lib", "content", "sample-media.ts"), "w", encoding="utf-8").write("\n".join(out))
print("ok")
