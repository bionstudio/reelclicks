/**
 * Cloudinary delivery helpers.
 *
 * Paste any Cloudinary video URL into the CMS, e.g.
 *   https://res.cloudinary.com/<cloud>/video/upload/v1712/reels/wedding.mp4
 * and it is automatically rewritten to an adaptive, compressed rendition:
 *   https://res.cloudinary.com/<cloud>/video/upload/f_auto,q_auto,vc_auto,w_1920,c_limit/v1712/reels/wedding.mp4
 */

const CLOUDINARY_UPLOAD = /^(https:\/\/res\.cloudinary\.com\/[^/]+\/video\/upload\/)(.*)$/;

export function isCloudinaryVideo(url: string) {
  return CLOUDINARY_UPLOAD.test(url);
}

function hasTransformations(path: string) {
  // first segment after /upload/ contains transformation params like "f_auto,q_auto"
  const first = path.split("/")[0] ?? "";
  return /(^|,)[a-z]{1,3}_[^/]+/.test(first) && !/^v\d+$/.test(first);
}

export function optimizeCloudinaryVideo(url: string, opts: { width?: number } = {}) {
  const m = url.match(CLOUDINARY_UPLOAD);
  if (!m) return url;
  const [, base, rest] = m;
  if (hasTransformations(rest)) return url;
  const t = ["f_auto", "q_auto", "vc_auto", `w_${opts.width ?? 1920}`, "c_limit"].join(",");
  return `${base}${t}/${rest}`;
}

/** Poster frame generated by Cloudinary from the video itself. */
export function cloudinaryPoster(url: string, second = 1) {
  const m = url.match(CLOUDINARY_UPLOAD);
  if (!m) return null;
  const [, base, rest] = m;
  const clean = rest.replace(/\.(mp4|mov|webm|m4v)$/i, ".jpg");
  return `${base}so_${second},f_auto,q_auto,w_1920,c_limit/${clean}`;
}
